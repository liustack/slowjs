// Command dtoatable writes engine/dtoa-pow10.h, the table of powers of ten
// that the shortest conversion of a float64 to decimal in engine/dtoa.c uses
// (the Schubfach algorithm of Raffaello Giulietti, written from his paper "The
// Schubfach way to render doubles"). It also checks the three integer formulas
// of dtoa.c that stand for floor(e*log10(2)), floor(log10(3/4*2^e)) and
// floor(e*log2(10)) over the exponents they are used for, and stops if one is
// wrong. Everything is computed with exact rationals.
//
//	go run ./internal/dtoatable > engine/dtoa-pow10.h
//
// The test of this package checks that the file in the tree is what this
// command writes.
package main

import (
	"bytes"
	"fmt"
	"io"
	"math/big"
	"os"
)

// The exponents of the table: 10^e for e in [pow10Min, pow10Max]. A float64
// is c*2^q with q in [-1074, 971], and the conversion reads 10^-k with
// k = floor(log10(2^q)) or floor(log10(3/4*2^q)), so k in [-324, 292].
const (
	pow10Min = -292
	pow10Max = 324
	qMin     = -1074
	qMax     = 971
)

func pow(base int64, e int) *big.Rat {
	p := new(big.Int).Exp(big.NewInt(base), big.NewInt(int64(abs(e))), nil)
	r := new(big.Rat).SetInt(p)
	if e < 0 {
		r.Inv(r)
	}
	return r
}

func abs(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

// floorLog returns the largest k with base^k <= x, for x > 0.
func floorLog(base int64, x *big.Rat) int {
	// start from the bit lengths and walk to the answer
	k := 0
	if base == 2 {
		k = x.Num().BitLen() - x.Denom().BitLen()
	} else {
		k = int(float64(x.Num().BitLen()-x.Denom().BitLen()) * 0.30102999566398120)
	}
	for pow(base, k).Cmp(x) > 0 {
		k--
	}
	for pow(base, k+1).Cmp(x) <= 0 {
		k++
	}
	return k
}

// The formulas of dtoa.c, with Go's arithmetic shift, which is C's on the
// targets (clang shifts a negative int arithmetically).
func floorLog10Pow2(e int) int              { return (e * 1262611) >> 22 }
func floorLog10ThreeQuartersPow2(e int) int { return (e*1262611 - 524031) >> 22 }
func floorLog2Pow10(e int) int              { return (e * 1741647) >> 19 }

func checkFormulas() error {
	return checkFormulasOf(floorLog10Pow2, floorLog10ThreeQuartersPow2, floorLog2Pow10)
}

func checkFormulasOf(log10Pow2, log10ThreeQuartersPow2, log2Pow10 func(int) int) error {
	three4 := big.NewRat(3, 4)
	for q := qMin; q <= qMax; q++ {
		p := pow(2, q)
		if got, want := log10Pow2(q), floorLog(10, p); got != want {
			return fmt.Errorf("floor(log10(2^%d)): formula %d, exact %d", q, got, want)
		}
		x := new(big.Rat).Mul(three4, p)
		if got, want := log10ThreeQuartersPow2(q), floorLog(10, x); got != want {
			return fmt.Errorf("floor(log10(3/4*2^%d)): formula %d, exact %d", q, got, want)
		}
	}
	for e := pow10Min; e <= pow10Max; e++ {
		if got, want := log2Pow10(e), floorLog(2, pow(10, e)); got != want {
			return fmt.Errorf("floor(log2(10^%d)): formula %d, exact %d", e, got, want)
		}
	}
	return nil
}

// entry returns g = floor(10^e * 2^-r) + 1 with r = floor(log2(10^e)) - 127,
// so that 2^127 < g <= 2^128 - 1: 10^e scaled to 128 bits and rounded up.
func entry(e int) *big.Int {
	x := pow(10, e)
	r := floorLog(2, x) - 127
	x.Mul(x, pow(2, -r))
	g := new(big.Int).Quo(x.Num(), x.Denom())
	g.Add(g, big.NewInt(1))
	lo := new(big.Int).Lsh(big.NewInt(1), 127)
	hi := new(big.Int).Lsh(big.NewInt(1), 128)
	if g.Cmp(lo) <= 0 || g.Cmp(hi) >= 0 {
		panic(fmt.Sprintf("10^%d: g out of range", e))
	}
	return g
}

func write(w io.Writer) error {
	if err := checkFormulas(); err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString(`/*
 * Copyright (c) 2026 The liustack/slowjs Authors.
 * SPDX-License-Identifier: MIT
 * Use of this source code is governed by the MIT license in LICENSE at the
 * root of this repository.
 *
 * Code generated by internal/dtoatable (go run ./internal/dtoatable). DO NOT EDIT.
 *
 * dtoa_pow10[e - DTOA_POW10_MIN] = { high 64 bits, low 64 bits } of
 * g = floor(10^e * 2^-r) + 1, r = floor(log2(10^e)) - 127, for the shortest
 * conversion of dtoa.c. 2^127 < g < 2^128.
 */
`)
	fmt.Fprintf(&b, "#define DTOA_POW10_MIN (%d)\n#define DTOA_POW10_MAX %d\n\n", pow10Min, pow10Max)
	b.WriteString("static const uint64_t dtoa_pow10[DTOA_POW10_MAX - DTOA_POW10_MIN + 1][2] = {\n")
	mask := new(big.Int).SetUint64(^uint64(0))
	for e := pow10Min; e <= pow10Max; e++ {
		g := entry(e)
		lo := new(big.Int).And(g, mask).Uint64()
		hi := new(big.Int).Rsh(g, 64).Uint64()
		fmt.Fprintf(&b, "    { 0x%016x, 0x%016x }, /* %d */\n", hi, lo, e)
	}
	b.WriteString("};\n")
	_, err := w.Write(b.Bytes())
	return err
}

func main() {
	if err := write(os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "dtoatable:", err)
		os.Exit(1)
	}
}
