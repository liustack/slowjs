const checkGenMarker = "// Code generated by internal/goasm/gen. DO NOT EDIT.\n"

// checkGenRepo is a git repository with scripts/check-gen.sh, a gen-engine.sh
// that writes two small files for the architecture it is asked for, and the
// same two files per architecture checked in under internal/cengine.
func checkGenRepo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	dir := t.TempDir()
	script, err := os.ReadFile(filepath.Join("..", "..", "..", "scripts", "check-gen.sh"))
	if err != nil {
		t.Fatal(err)
	}
	write := func(name, text string) {
		t.Helper()
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	write("scripts/check-gen.sh", string(script))
	// What the generator makes: by architecture, from its name.
	write("scripts/gen-engine.sh", `#!/bin/sh
set -eu
mkdir -p "$GEN_OUT"
for f in "engine_$1.s" "engine_decl_$1.go" "engine_keep_$1.go"; do
	printf '%s' '`+checkGenMarker+`body '"$1"'
' > "$GEN_OUT/$f"
done
`)
	write("internal/cengine/hand.go", "package cengine\n")
	for _, arch := range []string{"amd64", "arm64"} {
		for _, f := range []string{"engine_" + arch + ".s", "engine_decl_" + arch + ".go", "engine_keep_" + arch + ".go"} {
			write("internal/cengine/"+f, checkGenMarker+"body "+arch+"\n")
		}
	}
	git(t, dir, "init", "-q")
	git(t, dir, "add", "-A")
	git(t, dir, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "all")
	return dir
}

func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

func runCheckGen(dir string) (string, error) {
	cmd := exec.Command("sh", "scripts/check-gen.sh")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// TestCheckGenScript: check-gen takes the checked-in files from git, so a
// file git does not hold (ignored, or just not added) is not checked in, and
// it finds every generated file of the folder by its header, so one of a name
// the generator no longer makes is a file too many.
func TestCheckGenScript(t *testing.T) {
	dir := checkGenRepo(t)
	if out, err := runCheckGen(dir); err != nil {
		t.Fatalf("the files as generated: %v\n%s", err, out)
	}
	cengine := func(name string) string { return filepath.Join(dir, "internal", "cengine", name) }
	for name, c := range map[string]struct {
		edit func(t *testing.T)
		want string
	}{
		"ignored, not in git": {func(t *testing.T) {
			git(t, dir, "rm", "-q", "--cached", "internal/cengine/engine_decl_arm64.go")
			if err := os.WriteFile(filepath.Join(dir, ".git", "info", "exclude"), []byte("engine_decl_arm64.go\n"), 0o644); err != nil {
				t.Fatal(err)
			}
		}, "engine_decl_arm64.go"},
		"not added": {func(t *testing.T) {
			git(t, dir, "rm", "-q", "--cached", "internal/cengine/engine_keep_amd64.go")
		}, "engine_keep_amd64.go"},
		"changed": {func(t *testing.T) {
			if err := os.WriteFile(cengine("engine_arm64.s"), []byte(checkGenMarker+"other\n"), 0o644); err != nil {
				t.Fatal(err)
			}
		}, "engine_arm64.s is not what the generator makes"},
		"removed from the folder": {func(t *testing.T) {
			if err := os.Remove(cengine("engine_amd64.s")); err != nil {
				t.Fatal(err)
			}
		}, "engine_amd64.s"},
		"old name, in git": {func(t *testing.T) {
			if err := os.WriteFile(cengine("engine_decl.go"), []byte(checkGenMarker+"old\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			git(t, dir, "add", "internal/cengine/engine_decl.go")
		}, "engine_decl.go"},
		"old name, not in git": {func(t *testing.T) {
			if err := os.WriteFile(cengine("engine_negative.go"), []byte(checkGenMarker+"old\n"), 0o644); err != nil {
				t.Fatal(err)
			}
		}, "engine_negative.go"},
		"a name no rule lists": {func(t *testing.T) {
			if err := os.WriteFile(cengine("quickjs_3.s"), []byte(checkGenMarker+"old\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			git(t, dir, "add", "internal/cengine/quickjs_3.s")
		}, "quickjs_3.s"},
	} {
		d := checkGenRepo(t)
		dir = d
		c.edit(t)
		out, err := runCheckGen(d)
		if err == nil || !strings.Contains(out, c.want) {
			t.Errorf("%s: %v, want %q in\n%s", name, err, c.want, out)
		}
	}
	// A file by hand with no header is not the generator's concern.
	dir = checkGenRepo(t)
	if err := os.WriteFile(cengine("note.s"), []byte("// by hand\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "add", "internal/cengine/note.s")
	if out, err := runCheckGen(dir); err != nil {
		t.Errorf("a file by hand: %v\n%s", err, out)
	}
}
