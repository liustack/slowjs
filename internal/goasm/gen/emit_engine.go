// Emit for the whole engine: the functions go into several .s files (one or
// more per C source file, each under a size bound), engine_rodata into its
// own file as Go DATA, and every function the generator could not lower
// becomes a stub that reports its name to Go.
package gen

import (
	"fmt"
	"sort"
	"strings"
)

// EngineEmit says what to write.
type EngineEmit struct {
	Metas []Meta  // lowered functions, in output order
	Names NameMap // C symbol -> Go identifier
	// Group gives the file group of each function (its C source file);
	// MaxBytes bounds the size of one .s file.
	Group    map[string]string
	MaxBytes int
	// Stubs are functions emitted as a call to ·goasmMissing(index). With
	// NoStubs (a release build) any stub is an error.
	Stubs   []Meta
	NoStubs bool
	Plan    *DataPlan
	Arch    string // file name suffix and build tag
	// Align64 maps a function to where its body starts in a line of 64
	// bytes, a multiple of 8 below 64: a PCALIGN $64 takes the place of the
	// PCALIGN $16 after Go's prologue (which also puts the function itself
	// on 64 bytes), followed by that many bytes of 8-byte no-ops. The no-ops
	// run once per call. A change elsewhere in the program then moves the
	// body by whole lines of 64 bytes only.
	Align64 map[string]int
}

// EmitEngine returns the generated .s files by name.
func EmitEngine(objPath string, e EngineEmit) (map[string]string, error) {
	if e.NoStubs && len(e.Stubs) > 0 {
		var names []string
		for _, m := range e.Stubs {
			names = append(names, m.Name)
		}
		return nil, fmt.Errorf("a release build has no stub, but %d functions would be: %s", len(names), strings.Join(names, " "))
	}
	o, err := readObject(objPath)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("// Code generated by internal/goasm/gen. DO NOT EDIT.\n//go:build %s\n\n#include \"textflag.h\"\n#include \"funcdata.h\"\n\n", e.Arch)
	files := map[string]string{}
	parts := map[string]int{}
	cur := map[string]*strings.Builder{}
	open := func(group string, n int) *strings.Builder {
		b := cur[group]
		if b != nil && b.Len()+n > e.MaxBytes && b.Len() > len(header) {
			files[fmt.Sprintf("%s_%d_%s.s", group, parts[group], e.Arch)] = b.String()
			parts[group]++
			b = nil
		}
		if b == nil {
			b = &strings.Builder{}
			b.WriteString(header)
			cur[group] = b
		}
		return b
	}
	aligned := 0
	for _, m := range e.Metas {
		vs, ok := o.funcs[m.Name]
		if !ok {
			return nil, fmt.Errorf("symbol %s absent", m.Name)
		}
		var fb strings.Builder
		lo, hi := int(vs[0]), int(vs[0]+vs[1])
		gn := e.Names[m.Name]
		fb.WriteString(funcHeader(gn, m))
		if off, ok := e.Align64[m.Name]; ok {
			if off < 0 || off >= 64 || off%8 != 0 {
				return nil, fmt.Errorf("%s: body at %d bytes into a line of 64, not a multiple of 8 below 64", m.Name, off)
			}
			aligned++
			fmt.Fprintf(&fb, "\tPCALIGN $64\n")
			for ; off > 0; off -= 8 {
				fmt.Fprintf(&fb, "\tQUAD $0x0000000000841f0f // NOPL 0(AX)(AX*1)\n")
			}
		} else {
			fmt.Fprintf(&fb, "\tPCALIGN $16\n")
		}
		code := hi
		if cs, ok := o.funcs[m.Name+".const"]; ok {
			code = int(cs[0])
		}
		if err := emitFunc(&fb, o, lo, code, e.Names); err != nil {
			return nil, fmt.Errorf("%s: %w", m.Name, err)
		}
		if err := emitBytes(&fb, o.code[code:hi]); err != nil {
			return nil, fmt.Errorf("%s: %w", m.Name, err)
		}
		fmt.Fprintf(&fb, "\tRET\n\n")
		group := e.Group[m.Name]
		if group == "" {
			group = "engine"
		}
		open(group, fb.Len()).WriteString(fb.String())
	}
	if aligned != len(e.Align64) {
		return nil, fmt.Errorf("%d functions to put on 64 bytes, but only %d of them are lowered", len(e.Align64), aligned)
	}
	var groups []string
	for g := range cur {
		groups = append(groups, g)
	}
	sort.Strings(groups)
	for _, g := range groups {
		name := fmt.Sprintf("%s_%d_%s.s", g, parts[g], e.Arch)
		if parts[g] == 0 {
			name = fmt.Sprintf("%s_%s.s", g, e.Arch)
		}
		files[name] = cur[g].String()
	}
	if len(e.Stubs) > 0 {
		var b strings.Builder
		b.WriteString(header)
		b.WriteString("// Functions the generator could not lower: each reports its index.\n\n")
		for i, m := range e.Stubs {
			fmt.Fprintf(&b, "TEXT ·%s(SB), $8-%d\n\tNO_LOCAL_POINTERS\n\tMOVQ $%d, 0(SP)\n\tCALL ·goasmMissing(SB)\n\tRET\n\n", e.Names[m.Name], m.ArgBytes, i)
		}
		files["engine_stubs_"+e.Arch+".s"] = b.String()
	}
	if e.Plan != nil {
		files["engine_rodata_"+e.Arch+".s"] = EmitRodata(e.Plan, e.Names, header)
	}
	return files, nil
}

// EmitRodata writes engine_rodata as Go DATA: the bytes, the pointers to
// functions and to itself as relocations. Zero words are left to GLOBL.
func EmitRodata(p *DataPlan, names NameMap, header string) string {
	var b strings.Builder
	b.WriteString(header)
	n := len(p.Blob)
	if n == 0 {
		n = 8
	}
	size := alignUp(n, 8)
	fmt.Fprintf(&b, "GLOBL ·%s(SB), RODATA|NOPTR, $%d\n", RodataGo, size)
	blob := append(append([]byte(nil), p.Blob...), make([]byte, size-len(p.Blob))...)
	ri := 0
	for off := 0; off < size; {
		if ri < len(p.Relocs) && p.Relocs[ri].Off < off+8 {
			r := p.Relocs[ri]
			// bytes before the pointer
			for ; off < r.Off; off++ {
				if blob[off] != 0 {
					fmt.Fprintf(&b, "DATA ·%s+%d(SB)/1, $0x%02x\n", RodataGo, off, blob[off])
				}
			}
			target := RodataGo
			if r.Func {
				target = names[r.Sym]
			}
			if r.Add != 0 {
				fmt.Fprintf(&b, "DATA ·%s+%d(SB)/8, $·%s+%d(SB)\n", RodataGo, off, target, r.Add)
			} else {
				fmt.Fprintf(&b, "DATA ·%s+%d(SB)/8, $·%s(SB)\n", RodataGo, off, target)
			}
			off += 8
			ri++
			continue
		}
		if off%8 == 0 && off+8 <= size {
			v := le64(blob[off:])
			if v != 0 {
				fmt.Fprintf(&b, "DATA ·%s+%d(SB)/8, $0x%016x\n", RodataGo, off, v)
			}
			off += 8
			continue
		}
		if blob[off] != 0 {
			fmt.Fprintf(&b, "DATA ·%s+%d(SB)/1, $0x%02x\n", RodataGo, off, blob[off])
		}
		off++
	}
	return b.String()
}

// goReserved are names a generated Go declaration may not take.
var goReserved = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true, "default": true, "defer": true,
	"else": true, "fallthrough": true, "for": true, "func": true, "go": true, "goto": true, "if": true,
	"import": true, "interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
	"uintptr": true, "float64": true, "int64": true, "uint64": true, "string": true, "bool": true, "int": true,
	"byte": true, "error": true, "len": true, "cap": true, "new": true, "make": true, "append": true,
	"copy": true, "panic": true, "print": true, "println": true, "nil": true, "true": true, "false": true,
}

// GoNames maps C symbols to Go identifiers: dots (from LLVM's renaming of
// static functions with the same name) become underscores, and a name Go
// reserves gets a trailing underscore. Two C names mapping to one Go name is
// an error.
func GoNames(syms []string) (NameMap, error) {
	m := NameMap{}
	seen := map[string]string{}
	for _, s := range syms {
		g := strings.NewReplacer(".", "_", "$", "_").Replace(s)
		if goReserved[g] {
			g += "_"
		}
		if prev, ok := seen[g]; ok && prev != s {
			return nil, fmt.Errorf("C symbols %s and %s both map to Go %s", prev, s, g)
		}
		seen[g] = s
		m[s] = g
	}
	return m, nil
}
